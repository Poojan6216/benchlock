from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "bench" / "results"
OUT = ROOT / "README.md"


def load(name: str) -> dict:
    path = RESULTS / name
    if not path.exists():
        raise SystemExit(f"missing {path.relative_to(ROOT)} — run the benchmarks first")
    return json.loads(path.read_text())


def demo_block(section: str) -> str:
    text = (ROOT / "docs" / "demo.md").read_text()
    match = re.search(rf"## {re.escape(section)}.*?(```text\n.*?\n```)", text, re.S)
    if match is None:
        raise SystemExit(f"could not find {section!r} in docs/demo.md — run bench/demo.py")
    return match.group(1)


