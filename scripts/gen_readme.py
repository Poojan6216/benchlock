    b2_fa = stable["B2-bonferroni-t-test"]["alarm_rate"]
    b6_fa = stable["B6-benchlock"]["alarm_rate"]
    b1_wrong = judge["B1-peeking-t-test"]["verdicts"].get("regression", 0) / seeds
    b5_wrong = judge["B5-benchlock-no-anchor"]["verdicts"].get("regression", 0) / seeds
    b6_right = judge["B6-benchlock"]["verdicts"].get("judge", 0) / seeds

