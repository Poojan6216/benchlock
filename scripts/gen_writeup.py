#!/usr/bin/env python3
"""Generate docs/writeup.md — the technical post, with numbers read from committed runs."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "bench" / "results"
OUT = ROOT / "docs" / "writeup.md"


def load(name: str) -> dict:
    return json.loads((RESULTS / name).read_text())


def main() -> int:
    headline = load("sim-headline.json")
    summary = load("summary.json")["aggregates"]
    attacks = {r["strategy"]: r for r in load("adversarial-latest.json")["rows"]}
    fa = load("eprocess-false-alarm.json")
    nd = load("judge-nondeterminism.json")["rows"][0]
    refusals = load("judge-refusal-rates.json")
    by_cfg = {r["config"]: r for r in refusals["per_config"]}
    reps = refusals["replicates_same_config"]
    real = load("real-latest.json")
    b6_real = [r for r in real["rows"] if r["method"] == "B6-benchlock"]
    b6_real_ok = sum(1 for r in b6_real if r["correct"])

    b1_fa = headline["stable"]["B1-peeking-t-test"]["alarm_rate"]
    b6_fa = headline["stable"]["B6-benchlock"]["alarm_rate"]
    b1_delay = summary["antiresult.b1_mean_delay"]
    b6_delay = summary["antiresult.b6_mean_delay"]
    b5_mis = summary["grid.B5-benchlock-no-anchor.judge_as_system"]
    b6_mis = summary["grid.B6-benchlock.judge_as_system"]
    b6_indet = summary["grid.B6-benchlock.indeterminate"]

    OUT.write_text(f"""<!-- GENERATED by scripts/gen_writeup.py. Do not edit by hand. -->
# Your eval dashboard has been lying to you in two different ways

*And here is the arithmetic — including the part where our method is slower than the wrong one.*

---

## The verdict I am most pleased with is the one that refuses to answer

```text
verdict=indeterminate

- your system score moved, and the anchor set did not
- BUT the anchor set is under-provisioned: at n=40 the minimum judge shift this anchor
  process could have detected by run 55 is 0.044. The observed system move is 0.038.
  A judge shift of that size would be INVISIBLE here
- benchlock will not attribute this to your system. It cannot rule out the judge

Fix the provisioning, then this becomes decidable:
  benchlock plan --target-shift 0.05
```

There *was* a real regression in that stream. A tool that answered "system" would have been
right — by luck. Its anchor set was too small to have noticed a judge shift of the same
size, so it had no basis for ruling the judge out, and saying so is the only honest move
available.

**A tool that is confidently wrong one time in ten is worse than useless in a CI gate,
because people learn to ignore it.** That is the whole design brief.

---

## Lie one: the number you look at every day

You run evals in CI. A number comes out. You look at it on every commit.

If you test that number with a t-test at α = 0.05, re-run each time, your false-alarm rate
is not 5%. Over {headline["seeds"]} drift-free streams inspected after every one of
{headline["monitored_runs"]} runs:

| | false alarm on a healthy pipeline |
|---|---:|
| t-test re-run every run | **{b1_fa:.1%}** |
| the same, Bonferroni-corrected | **{headline["stable"]["B2-bonferroni-t-test"]["alarm_rate"]:.1%}** |
| anytime-valid | **{b6_fa:.1%}** |

Peeking is not a misuse of the test. It *is* the workflow. And Bonferroni over
runs-so-far — the obvious fix — still lands above α, because the tests are not independent.

The fix is old and pip-installable: sequential analysis, e-values, Ville's inequality
(1939). A non-negative martingale that starts at 1 satisfies `P(ever exceeding 1/α) ≤ α`,
**for all time simultaneously.** You can look as often as you like.

There is a second lie hiding in that one. The baseline mean is not known — it is estimated.
Monitoring against its point estimate is the natural implementation and it is invalid: over
{fa["streams"]:,} drift-free streams it false-alarmed
**{fa["point_estimate_false_alarm_rate"]:.1%}** of the time,
{fa["point_estimate_over_alpha_factor"]}× its own α. Roughly half of all healthy pipelines.

---

## Lie two: "the score dropped, so the system regressed"

The judge is a hosted model. Providers rotate snapshots, adjust safety post-processing,
change defaults. Your teammate edits the rubric. Any of these moves the score with **zero
change** to the thing you are trying to measure.

Every single-stream method has exactly one conclusion available to it: "something moved".
On streams where only the judge moved:

| method | what it concludes |
|---|---|
| fixed threshold, t-test, Bonferroni, CUSUM | "regression", 100% of the time |
| the same statistics with no control group | "regression", 100% of the time |
| **with a frozen anchor set** | `judge`, 100% of the time |

The fix is not clever. Freeze a set of `(item, output)` pairs the system never touches, and
have the judge re-score them every run. If those move, only the judge can have moved them.
It is difference-in-differences, with the anchor set as the control group.

Across the full grid, judge-to-system misattribution is **{b5_mis:.2f}** without a control
group and **{b6_mis:.2f}** with one — with **{b6_indet:.2f}** landing in `indeterminate`
rather than being guessed at.

---

## The part where we are worse

**Anytime-valid tests detect later than invalid ones.** Not marginally:

| | peeking t-test | anytime-valid |
|---|---:|---:|
| mean median detection delay | **{b1_delay:.1f} runs** | **{b6_delay:.1f} runs** |
| false alarm on healthy pipelines | **{b1_fa:.1%}** | **{b6_fa:.1%}** |

Roughly **{b6_delay / b1_delay:.0f}× slower**. That is the price, it is real, and if a
false rollback is cheap for you while slow detection is expensive, the t-test is the better
tool and you should use it.

---

## No human labels, and why that is allowed

The obvious objection to a frozen anchor set: doesn't a control group need ground truth?

No — and this is the observation the whole design rests on:

> **Attribution needs judge *stability*, not judge *validity*.**

We are not asking whether the judge is right. We are asking whether it is the same judge it
was last week. A snapshot of the judge's *own* scores answers that exactly, and costs
nothing to produce.

The cost is real and stated in the README's first screen: a judge that was always wrong
stays consistently wrong and correctly reads as **stable**. Benchlock does not claim your
evals are correct.

---

## What beats it

Six of eight adversarial strategies work at some rate. The one that matters:

**Anchor evasion — {attacks["7.1 anchor evasion"]["failure_rate"]:.0%}.** A judge that got
stricter only about code responses, while your anchors are all prose, is invisible to the
anchor stream. The system stream moves, the anchor stream does not, and you get `system` —
a confident, wrong rollback recommendation, produced by the tool built to prevent exactly
that.

Stratified selection and coverage warnings make it less likely. **Nothing makes it go
away.** Coverage is measured; it is never guaranteed.

Also working: a rubric you changed on purpose is indistinguishable from provider drift
({attacks["7.4 anchor staleness"]["failure_rate"]:.0%}); a suite whose ids are stable while
its content shifts slips past the fixed-suite check
({attacks["7.5 input distribution shift"]["failure_rate"]:.0%}); and a provider that caches
judge responses makes the anchor set return yesterday's answers, hiding drift entirely
unless you add a cache-busting nonce
({attacks["7.9 provider-side response caching"]["failure_rate"]:.0%} without one).

---

## Two things I did not expect to find

**A temperature-0 judge disagrees with itself {nd["self_disagreement_rate"]:.1%} of the
time.** Five identical calls per item, cache-busting nonce so nothing was served from a
cache: {nd["items_that_ever_varied_rate"]:.0%} of items came back with a different score at
least once. The run mean wobbles by {nd["run_mean_sd"]:.4f} between identical runs. That is
the noise floor, it is not zero, and it will move your dashboard on its own.

More interesting: that wobble is **{nd["independence_ratio"]:.2f}x larger** than independent
per-item noise predicts. The judge shifts every item together — which means a bigger anchor
set buys *less* than `1/sqrt(n)` of precision. The provisioning calculator models that as a
`shared_sd` term; I put it in on theoretical grounds and the real judge confirmed it.

**And a judge's willingness to score at all is a form of drift nobody watches.** Editing
only the rubric text — same model, same items — raised the refusal rate from
{by_cfg["a-baseline"]["refusal_rate"]:.1%} to {by_cfg["c-strict-rubric"]["refusal_rate"]:.1%}.
Raising only the reasoning effort took it to {by_cfg["d-effort"]["refusal_rate"]:.1%}. Five
identical repeats of the same 200 items declined between {reps["min_refused"]} and
{reps["max_refused"]} of them, so the refusal boundary is not even deterministic.

That last one is a hole in this tool. Benchlock watches scores; a refused item silently
leaves the sample. On the one real-judge scenario Benchlock gets wrong — the effort change —
the configuration moved refusals without moving scores, and the verdict came back `stable`.
{b6_real_ok} of {len(b6_real)} correct is the honest number, and the sixth is in the results
table.

---

*Everything above regenerates from committed data:* `uv run python scripts/gen_results.py`.
""")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
